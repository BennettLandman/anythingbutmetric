"""Vendor the catalog's Twemoji v14.0.2 artwork for offline, self-contained signs.

Run: python3 tools/sync-emoji.py --node /path/to/node
Artwork: Twitter, Inc and other contributors, CC BY 4.0.
"""
import argparse
import base64
from concurrent.futures import ThreadPoolExecutor
import json
from pathlib import Path
import subprocess
from urllib.request import Request, urlopen

parser = argparse.ArgumentParser()
parser.add_argument('--node', default='node')
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
source = 'https://raw.githubusercontent.com/twitter/twemoji/v14.0.2/'
emojis = json.loads(subprocess.check_output([
    args.node, '--input-type=module', '-e',
    "import {dimensions} from './engine.mjs'; console.log(JSON.stringify([...new Set(Object.values(dimensions).flatMap(d=>d.refs.map(r=>r.emoji)))]));"
], cwd=root, text=True))

# Reuse already-vendored artwork from this exact pinned release.
asset_file = root / 'assets' / 'emoji-art.mjs'
cached = {}
if asset_file.exists():
    existing = asset_file.read_text()
    if existing.startswith('// Twemoji v14.0.2 artwork'):
        cached = json.loads(existing.split('export const emojiArt = ', 1)[1].rstrip(';\n'))

def fetch(path):
    with urlopen(Request(source + path, headers={'User-Agent': 'AnythingButMetric asset sync'}), timeout=30) as response:
        return response.read()

def artwork(emoji):
    if emoji in cached:
        return emoji, cached[emoji]
    # Twemoji omits VS16 in simple emoji filenames, retaining it in ZWJ sequences.
    codepoints = [ord(c) for c in emoji]
    if 0x200d not in codepoints:
        codepoints = [c for c in codepoints if c != 0xfe0f]
    identifier = '-'.join(format(c, 'x') for c in codepoints)
    svg = fetch('assets/svg/' + identifier + '.svg')
    assert b'<svg' in svg and b'<script' not in svg and b'<foreignObject' not in svg
    return emoji, 'data:image/svg+xml;base64,' + base64.b64encode(svg).decode()

with ThreadPoolExecutor(max_workers=8) as pool:
    assets = dict(pool.map(artwork, emojis))
(root / 'assets').mkdir(exist_ok=True)
(root / 'assets' / 'emoji-art.mjs').write_text(
    '// Twemoji v14.0.2 artwork, Twitter, Inc and other contributors, CC BY 4.0.\n'
    '// Generated by tools/sync-emoji.py. See EMOJI-LICENSE.txt and README.md.\n'
    'export const emojiArt = ' + json.dumps(assets, ensure_ascii=False, sort_keys=True) + ';\n'
)
if not cached or not (root / 'EMOJI-LICENSE.txt').exists():
    (root / 'EMOJI-LICENSE.txt').write_bytes(fetch('LICENSE-GRAPHICS'))
print(f'Vendored {len(assets)} emoji symbols, including their full license.')
